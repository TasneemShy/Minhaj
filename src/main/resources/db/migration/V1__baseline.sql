-- V1: baseline schema.
-- Generated from the JPA entities (Hibernate ddl-auto=create on Postgres, dumped with pg_dump)
-- and tidied up. Constraint names match what Hibernate generated, so databases built earlier by
-- ddl-auto=update (which Flyway baselines at V1 instead of running this file) have the same names.
-- Never edit this file once applied; add a V2__... migration instead.

CREATE TABLE users (
    id       bigint GENERATED BY DEFAULT AS IDENTITY,
    name     varchar(255) NOT NULL,
    email    varchar(255) NOT NULL,
    password varchar(255) NOT NULL,
    role     varchar(255),
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE categories (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    name        varchar(255) NOT NULL,
    description text,
    CONSTRAINT categories_pkey PRIMARY KEY (id),
    CONSTRAINT categories_name_key UNIQUE (name)
);

CREATE TABLE courses (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    title          varchar(255) NOT NULL,
    description    text,
    is_free        boolean NOT NULL,
    price          double precision NOT NULL,
    lesson_count   integer NOT NULL,
    review_count   integer NOT NULL,
    average_rating double precision NOT NULL,
    image_url      varchar(255),
    category_id    bigint,
    instructor_id  bigint,
    created_at     timestamp(6) without time zone,
    updated_at     timestamp(6) without time zone,
    CONSTRAINT courses_pkey PRIMARY KEY (id),
    CONSTRAINT fk72l5dj585nq7i6xxv1vj51lyn FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fkcyfum8goa6q5u13uog0563gyp FOREIGN KEY (instructor_id) REFERENCES users (id)
);

CREATE TABLE lessons (
    id        bigint GENERATED BY DEFAULT AS IDENTITY,
    title     varchar(255) NOT NULL,
    video_url varchar(255),
    course_id bigint NOT NULL,
    CONSTRAINT lessons_pkey PRIMARY KEY (id),
    CONSTRAINT fk17ucc7gjfjddsyi0gvstkqeat FOREIGN KEY (course_id) REFERENCES courses (id)
);

CREATE TABLE reviews (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    comment    varchar(255) NOT NULL,
    rating     integer NOT NULL,
    course_id  bigint NOT NULL,
