-- Refresh tokens are stored only as the SHA-256 hex hash of the token the client holds.
-- A rotated token is revoked and points at the token that replaced it.
CREATE TABLE refresh_tokens (
    id             bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id        bigint NOT NULL,
    token_hash     varchar(64) NOT NULL,
    expires_at     timestamp(6) with time zone NOT NULL,
    created_at     timestamp(6) with time zone NOT NULL,
    revoked_at     timestamp(6) with time zone,
    replaced_by_id bigint,
    CONSTRAINT refresh_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT refresh_tokens_token_hash_key UNIQUE (token_hash),
    CONSTRAINT refresh_tokens_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT refresh_tokens_replaced_by_id_fkey FOREIGN KEY (replaced_by_id) REFERENCES refresh_tokens (id)
        ON DELETE SET NULL
);

-- Revoking every token of a user (logout everywhere, password change, reuse detection)
CREATE INDEX refresh_tokens_user_id_idx ON refresh_tokens (user_id);

-- Email verification. Accounts that already exist are treated as verified so nobody gets locked out
-- of the gated actions; new registrations start unverified (the application always sets the value).
ALTER TABLE users ADD COLUMN email_verified boolean;
UPDATE users SET email_verified = TRUE;
ALTER TABLE users ALTER COLUMN email_verified SET NOT NULL;

-- Emailed verification links; like password_reset_token, only the SHA-256 hex hash is stored.
CREATE TABLE email_verification_tokens (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id    bigint NOT NULL,
    token_hash varchar(64) NOT NULL,
    expires_at timestamp(6) with time zone NOT NULL,
    created_at timestamp(6) with time zone NOT NULL,
    CONSTRAINT email_verification_tokens_pkey PRIMARY KEY (id),
    CONSTRAINT email_verification_tokens_token_hash_key UNIQUE (token_hash),
    CONSTRAINT email_verification_tokens_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX email_verification_tokens_user_id_idx ON email_verification_tokens (user_id);
