-- V6: auto-graded lesson quizzes.
--
-- A lesson has at most one quiz (UNIQUE lesson_id). A quiz has ordered questions, a question has ordered
-- options, and some of those options are the correct ones. Students submit attempts, which are graded by the
-- application and stored with the options they selected.
--
-- Every foreign key cascades on delete, so removing a lesson (or a course, whose lessons are bulk-deleted by
-- CourseService.deleteCourse) or a user removes its quiz data without the application deleting it row by row.
-- New, empty tables: no locking or backfill concerns.

CREATE TABLE quizzes (
    id              bigint GENERATED BY DEFAULT AS IDENTITY,
    lesson_id       bigint NOT NULL,
    title           varchar(255) NOT NULL,
    pass_percentage integer NOT NULL DEFAULT 70,
    created_at      timestamp(6) without time zone NOT NULL,
    CONSTRAINT quizzes_pkey PRIMARY KEY (id),
    CONSTRAINT quizzes_lesson_id_key UNIQUE (lesson_id),
    CONSTRAINT quizzes_lesson_id_fkey FOREIGN KEY (lesson_id) REFERENCES lessons (id) ON DELETE CASCADE,
    CONSTRAINT quizzes_pass_percentage_check CHECK (pass_percentage BETWEEN 0 AND 100)
);

CREATE TABLE quiz_questions (
    id       bigint GENERATED BY DEFAULT AS IDENTITY,
    quiz_id  bigint NOT NULL,
    position integer NOT NULL,
    text     varchar(1000) NOT NULL,
    type     varchar(20) NOT NULL,
    CONSTRAINT quiz_questions_pkey PRIMARY KEY (id),
    CONSTRAINT quiz_questions_quiz_id_position_key UNIQUE (quiz_id, position),
    CONSTRAINT quiz_questions_quiz_id_fkey FOREIGN KEY (quiz_id) REFERENCES quizzes (id) ON DELETE CASCADE,
    CONSTRAINT quiz_questions_type_check CHECK (type IN ('SINGLE_CHOICE', 'MULTIPLE_CHOICE'))
);

CREATE TABLE quiz_options (
    id          bigint GENERATED BY DEFAULT AS IDENTITY,
    question_id bigint NOT NULL,
    position    integer NOT NULL,
    text        varchar(1000) NOT NULL,
    correct     boolean NOT NULL,
    CONSTRAINT quiz_options_pkey PRIMARY KEY (id),
    CONSTRAINT quiz_options_question_id_position_key UNIQUE (question_id, position),
    CONSTRAINT quiz_options_question_id_fkey FOREIGN KEY (question_id) REFERENCES quiz_questions (id) ON DELETE CASCADE
);

CREATE TABLE quiz_attempts (
    id               bigint GENERATED BY DEFAULT AS IDENTITY,
    quiz_id          bigint NOT NULL,
    user_id          bigint NOT NULL,
    score_percentage integer NOT NULL,
    passed           boolean NOT NULL,
    submitted_at     timestamp(6) without time zone NOT NULL,
    CONSTRAINT quiz_attempts_pkey PRIMARY KEY (id),
    CONSTRAINT quiz_attempts_quiz_id_fkey FOREIGN KEY (quiz_id) REFERENCES quizzes (id) ON DELETE CASCADE,
    CONSTRAINT quiz_attempts_user_id_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT quiz_attempts_score_percentage_check CHECK (score_percentage BETWEEN 0 AND 100)
);

-- Per-quiz analytics, and "has this student passed" for the manual completion check
CREATE INDEX quiz_attempts_quiz_id_user_id_idx ON quiz_attempts (quiz_id, user_id);
-- A student's own history
CREATE INDEX quiz_attempts_user_id_idx ON quiz_attempts (user_id);

-- One row per selected option. question_id is redundant with the option's question but keeps the stored
-- answer readable on its own.
CREATE TABLE quiz_attempt_answers (
    attempt_id  bigint NOT NULL,
    question_id bigint NOT NULL,
    option_id   bigint NOT NULL,
    CONSTRAINT quiz_attempt_answers_pkey PRIMARY KEY (attempt_id, option_id),
    CONSTRAINT quiz_attempt_answers_attempt_id_fkey FOREIGN KEY (attempt_id) REFERENCES quiz_attempts (id) ON DELETE CASCADE,
    CONSTRAINT quiz_attempt_answers_question_id_fkey FOREIGN KEY (question_id) REFERENCES quiz_questions (id) ON DELETE CASCADE,
    CONSTRAINT quiz_attempt_answers_option_id_fkey FOREIGN KEY (option_id) REFERENCES quiz_options (id) ON DELETE CASCADE
);

-- Indexes for the cascading deletes from questions and options
CREATE INDEX quiz_attempt_answers_question_id_idx ON quiz_attempt_answers (question_id);
CREATE INDEX quiz_attempt_answers_option_id_idx ON quiz_attempt_answers (option_id);
