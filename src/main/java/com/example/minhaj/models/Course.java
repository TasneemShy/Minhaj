package com.example.minhaj.models;

import jakarta.persistence.*;
import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.annotation.LastModifiedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

@Entity
@Table(name = "courses")
@EntityListeners(AuditingEntityListener.class)
public class Course {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false)
    private String title;

    @Column(columnDefinition = "TEXT")
    private String description;

    private boolean isFree;

    private double price;

    private int lessonCount = 0;
    private int reviewCount = 0;

    private double averageRating = 0.0;

    @CreatedDate
    @Column(updatable = false)
    private java.time.LocalDateTime createdAt;

    @LastModifiedDate
    private java.time.LocalDateTime updatedAt;

    @ManyToMany(mappedBy = "enrolledCourses", fetch = FetchType.LAZY)
    private java.util.Set<User> enrolledStudents = new java.util.HashSet<>();

    // Getters and Setters
    public Long getId() { return id; }
    public void setId(Long id) { this.id = id; }

    public String getTitle() { return title; }
    public void setTitle(String title) { this.title = title; }

    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public boolean isFree() { return isFree; }
    public void setFree(boolean free) { isFree = free; }

    public double getPrice() { return price; }
    public void setPrice(double price) { this.price = price; }

    public int getLessonCount() { return lessonCount; }
    public void setLessonCount(int lessonCount) { this.lessonCount = lessonCount; }

    public int getReviewCount() { return reviewCount; }
    public void setReviewCount(int reviewCount) { this.reviewCount = reviewCount; }

    public double getAverageRating() { return averageRating; }
    public void setAverageRating(double averageRating) { this.averageRating = averageRating; }

    public java.time.LocalDateTime getCreatedAt() { return createdAt; }
    public void setCreatedAt(java.time.LocalDateTime createdAt) { this.createdAt = createdAt; }

    public java.time.LocalDateTime getUpdatedAt() { return updatedAt; }
    public void setUpdatedAt(java.time.LocalDateTime updatedAt) { this.updatedAt = updatedAt; }

    public java.util.Set<User> getEnrolledStudents() { return enrolledStudents; }
    public void setEnrolledStudents(java.util.Set<User> enrolledStudents) { this.enrolledStudents = enrolledStudents; }

    @Column(name = "image_url")
    private String imageUrl;

    public String getImageUrl() {
        return imageUrl;
    }

    public void setImageUrl(String imageUrl) {
        this.imageUrl = imageUrl;
    }

    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "category_id")
    private Category category;

    public Category getCategory() { return category; }
    public void setCategory(Category category) { this.category = category; }

    // Owning instructor (null for courses created by an admin). Set by the server.
    @ManyToOne(fetch = FetchType.EAGER)
    @JoinColumn(name = "instructor_id")
    private User instructor;

    public User getInstructor() { return instructor; }
    public void setInstructor(User instructor) { this.instructor = instructor; }

    // New courses start as drafts; see CourseService.publish/unpublish.
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private CourseStatus status = CourseStatus.DRAFT;

    // First time the course was published; kept on unpublish and re-publish. Null if never published.
    @Column(name = "published_at")
    private java.time.LocalDateTime publishedAt;

    public CourseStatus getStatus() { return status; }
    public void setStatus(CourseStatus status) { this.status = status; }

    public boolean isPublished() { return status == CourseStatus.PUBLISHED; }

    public java.time.LocalDateTime getPublishedAt() { return publishedAt; }
    public void setPublishedAt(java.time.LocalDateTime publishedAt) { this.publishedAt = publishedAt; }

    // Full-text search vector of title + description, generated by Postgres (V5__course_search.sql).
    // Mapped read-only only so CourseSpecifications can reference it in Criteria queries; Hibernate never
    // writes it, and columnDefinition makes ddl-auto=validate accept the tsvector column. No getter on purpose.
    @Column(name = "search_vector", columnDefinition = "tsvector", insertable = false, updatable = false)
    private String searchVector;
}
